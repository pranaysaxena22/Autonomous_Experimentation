"""Builds docs/ingest_messages.md: every message the data reader can show, with the test that proves it and the message that test produced.

The text comes from the message catalogue and from running the tests, so it cannot drift from what the program says. The health check
regenerates it and fails if the saved file is out of date or if any message has no test.
"""
from __future__ import annotations

from pathlib import Path

from checks.ingest_cases import CaseResult, run_all, uncovered
from cellpoc.ingest import CATALOGUE
from cellpoc.ingest.fixed_rules import FIXED_RULES

DOC_PATH = Path(__file__).resolve().parents[1] / "docs" / "ingest_messages.md"
LEVEL_WORDS = {"error": "Error: the file cannot be used", "warning": "Warning: read, but something was assumed or repaired", "note": "Note: for information"}
GROUPS = [("The file cannot be used", "error"), ("Read, with an assumption or a repair you should know about", "warning"), ("Information", "note")]


def build_text(results: list[CaseResult] | None = None) -> str:
    results = results if results is not None else run_all()
    by_key: dict[tuple[str, str], list[CaseResult]] = {}
    for result in results:
        by_key.setdefault((result.case.rule, result.case.variant), []).append(result)
    missing = uncovered()
    lines = [
        "# Data reader messages",
        "",
        "_Generated by `tools/make_ingest_messages.py`. Do not edit by hand: change the wording in `cellpoc/ingest/findings.py` and run the tool again. "
        "The health check fails if this file is out of date._",
        "",
        "When the reader opens a data file it reports what it found in this form:",
        "",
        "> **File › Column:** what happened and what to do",
        "",
        "- **Error**: the file cannot be used until the problem is fixed.",
        "- **Warning**: the file was read, but the reader had to assume or repair something. Read these.",
        "- **Note**: information about how the file was read.",
        "",
        "Nothing is ever filled in or guessed silently: every repair is listed here. Every message below has a test: a small file made to cause exactly "
        "that message. The message shown is the one the test produced (the file name in the tests is `t.csv`).",
        "",
        f"**{len(CATALOGUE)} messages, {len(CATALOGUE) - len(missing)} tested, {len(missing)} without a test.**",
        "",
        "## Fixed rules the reader applies",
        "",
        "These never change and are never hidden: whenever one of them changes what a number or date means, a message above says so.",
        "",
        *[f"- {rule}" for rule in FIXED_RULES],
        "",
    ]
    for title, level in GROUPS:
        keys = sorted(k for k, rule in CATALOGUE.items() if rule.level == level)
        if not keys:
            continue
        lines += [f"## {title}", ""]
        for key in keys:
            rule = CATALOGUE[key]
            lines += [f"### {rule.id}" + (f" ({rule.variant})" if rule.variant else ""), "", f"- **Level:** {LEVEL_WORDS[rule.level]}", f"- **Checks that:** {rule.what}"]
            tests = by_key.get(key, [])
            if not tests:
                lines += ["- **Test:** NONE: this message has no test yet", ""]
                continue
            for result in tests:
                lines += [f"- **Test:** {result.case.what}", f"- **Message:** {result.finding.message if result.finding else '(the test did not produce it)'}"]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_doc(text: str | None = None) -> Path:
    DOC_PATH.write_bytes((text if text is not None else build_text()).encode("utf-8"))
    return DOC_PATH
