"""Builds docs/setup_messages.md: every setup rule with the test that proves it and the message a person sees.

The text comes from the message catalogue and from running the rule tests, so it cannot drift from what the program says.
The health check regenerates it and fails if the saved file is out of date, or if any rule has no test.
"""
from __future__ import annotations

from pathlib import Path

from checks.setup_cases import CaseResult, run_all, uncovered
from cellpoc.setup import CATALOGUE, SCREENS, SETUP_FILE_SCREEN

DOC_PATH = Path(__file__).resolve().parents[1] / "docs" / "setup_messages.md"
GENERAL = "General messages (any screen)"
LEVEL_WORDS = {"error": "Error: blocks saving", "warning": "Warning: does not block saving", "note": "Note: for information"}


def build_text(results: list[CaseResult] | None = None) -> str:
    results = results if results is not None else run_all()
    by_key: dict[tuple[str, str], list[CaseResult]] = {}
    for result in results:
        by_key.setdefault((result.case.rule, result.case.variant), []).append(result)
    groups: dict[str, list[tuple[str, str]]] = {}
    for key, rule in CATALOGUE.items():
        if rule.id.startswith("S"):
            shown = GENERAL                      # the generic messages can appear on any screen
        else:
            shown = next((r.problem.screen for r in by_key.get(key, []) if r.problem), rule.screen or "Other")
        groups.setdefault(shown, []).append(key)
    order = [SETUP_FILE_SCREEN, GENERAL] + SCREENS + ["Other"]
    missing = uncovered()
    lines = [
        "# Setup messages",
        "",
        "_Generated by `tools/make_setup_messages.py`. Do not edit by hand: change the wording in "
        "`cellpoc/setup/messages.py` and run the tool again. The health check fails if this file is out of date._",
        "",
        "When a setup has a problem, the setup app shows a message in this form:",
        "",
        "> **Screen › Field:** what is wrong and how to fix it",
        "",
        "There are three levels:",
        "",
        "- **Error**: blocks saving until fixed.",
        "- **Warning**: shown, but does not block saving.",
        "- **Note**: information only.",
        "",
        "Every rule below has a test: a deliberately wrong setup that must produce that message. "
        "The message shown under each rule is the one the test produced. "
        "What the person typed is quoted back in the message (for example `(you wrote '...')`).",
        "",
        f"**{len(CATALOGUE)} messages, {len(CATALOGUE) - len(missing)} tested, {len(missing)} without a test.**",
        "",
    ]
    for screen in order:
        keys = sorted(groups.get(screen, []))
        if not keys:
            continue
        lines += [f"## {screen}", ""]
        if screen == GENERAL:
            lines += ["_Used when a value is the wrong kind or out of range and no more specific message applies. "
                      "The screen and field in the message show where._", ""]
        for key in keys:
            rule = CATALOGUE[key]
            heading = f"### {rule.id}" + (f" ({rule.variant.replace('_', ' ')})" if rule.variant else "")
            lines += [heading, "", f"- **Level:** {LEVEL_WORDS[rule.level]}", f"- **Checks that:** {rule.what}"]
            tests = by_key.get(key, [])
            if not tests:
                lines += ["- **Test:** NONE: this rule has no test yet", ""]
                continue
            for result in tests:
                lines.append(f"- **Test:** {result.case.what}")
                lines.append(f"- **Message:** {result.problem.message if result.problem else '(the test did not produce it)'}")
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_doc(text: str | None = None) -> Path:
    DOC_PATH.write_bytes((text if text is not None else build_text()).encode("utf-8"))   # Unix line endings, no byte-order mark
    return DOC_PATH
