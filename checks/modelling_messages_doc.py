"""Builds docs/modelling_messages.md: every message the modelling part can show, with the test that proves it and the message that test produced.

The text comes from the message catalogue and from running the tests, so it cannot drift from what the program says. The health check
regenerates it and fails if the saved file is out of date or if any message has no test.
"""
from __future__ import annotations

from pathlib import Path

from cellpoc.modelling import CATALOGUE
from checks.modelling_cases import CaseResult, run_all, uncovered

DOC_PATH = Path(__file__).resolve().parents[1] / "docs" / "modelling_messages.md"
LEVEL_WORDS = {"error": "Error: the table cannot be modelled", "warning": "Warning: something was left out or limited", "note": "Note: carried into every report"}
GROUPS = [("The table cannot be modelled", "error"), ("Something was left out or limited", "warning"), ("Facts every report must carry", "note")]


def build_text(results: list[CaseResult] | None = None) -> str:
    results = results if results is not None else run_all()
    by_key: dict[tuple[str, str], list[CaseResult]] = {}
    for result in results:
        by_key.setdefault((result.case.rule, result.case.variant), []).append(result)
    missing = uncovered()
    lines = [
        "# Modelling messages",
        "",
        "_Generated by `tools/make_modelling_messages.py`. Do not edit by hand: change the wording in `cellpoc/modelling/findings.py` and run the tool again. "
        "The health check fails if this file is out of date._",
        "",
        "When a cleaned table is prepared for modelling, the program reports every decision in this form:",
        "",
        "> **Table > Result or input:** what happened and what to do",
        "",
        "- **Error**: the table cannot be modelled until the problem is fixed.",
        "- **Warning**: rows or inputs were left out, or a result is not modelled. Read these.",
        "- **Note**: facts that every report carries (a balance ingredient left out, rows flagged, an assumed unit, a stand-in for the supplier).",
        "",
        "Nothing is ever filled in or guessed silently, and no row is ever moved between training and test data at random. "
        "Every message below has a test: a tiny made-up table made to cause exactly that message (the table is called `t` in the tests).",
        "",
        f"**{len(CATALOGUE)} messages, {len(CATALOGUE) - len(missing)} tested, {len(missing)} without a test.**",
        "",
    ]
    for title, level in GROUPS:
        keys = sorted(k for k, rule in CATALOGUE.items() if rule.level == level)
        if not keys:
            continue
        lines += [f"## {title}", ""]
        for key in keys:
            rule = CATALOGUE[key]
            lines += [f"### {rule.id}" + (f" ({rule.variant})" if rule.variant else ""), "", f"- **Level:** {LEVEL_WORDS[rule.level]}", f"- **Checks that:** {rule.what}"]
            tests = by_key.get(key, [])
            if not tests:
                lines += ["- **Test:** NONE: this message has no test yet", ""]
                continue
            for result in tests:
                lines += [f"- **Test:** {result.case.what}", f"- **Message:** {result.finding.message if result.finding else '(the test did not produce it)'}"]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def write_doc(text: str | None = None) -> Path:
    DOC_PATH.write_bytes((text if text is not None else build_text()).encode("utf-8"))
    return DOC_PATH
