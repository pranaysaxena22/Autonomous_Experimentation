"""Writes docs/platform_formats/trial8_story.md: a plain-language table of what happened in the example trial.

Generated from the executed timeline (with the layout and setup for names), so it can never disagree with it.
A format check regenerates the text and fails if the file on disk differs, so do not edit the story by hand:
change the timeline and run this script again.

Usage:  python tools/make_trial_story.py            (writes the file)
        python tools/make_trial_story.py --print    (shows it without writing)
ILLUSTRATIVE: the example files are hand-authored and the values are made up.
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
FORMATS = ROOT / "docs" / "platform_formats"
OUT = FORMATS / "trial8_story.md"
QUANTITY_WORDS = {"mass_g": "mass", "hardness_kp": "hardness", "friability_pct": "friability", "dissolution_30min_pct": "dissolution at 30 min", "barcode": "barcode"}
UNIT_WORDS = {"mass_g": "g", "hardness_kp": "kP", "friability_pct": "%", "dissolution_30min_pct": "%", "barcode": ""}


def _hms(seconds: float) -> str:
    s = int(round(seconds))
    return f"{s // 3600}:{s % 3600 // 60:02d}:{s % 60:02d}"


def _length(seconds: float) -> str:
    return f"{seconds / 60:.0f} min" if seconds >= 120 else f"{seconds:g} s"


def build_story(executed: dict, layout: dict, setup: dict) -> str:
    labels = {i["id"]: i["label"] for i in setup["ingredients"]}
    stations = {s["id"]: s["label"] for s in layout["stations"]}
    slots = {s["id"]: f"Bottle slot {s['id'].split('_')[1]} ({labels[s['ingredient_id']].split(' (')[0]})" for s in layout["bottle_shelf"]["slots"]}
    holders = {h["id"]: f"{h['tool'].capitalize()} holder" for h in layout["tool_holders"]}
    place = {**stations, **slots, **holders, "home": "Home pose"}
    objects = {}
    for o in layout["objects"]:
        if o["type"] == "bottle":
            objects[o["id"]] = f"{labels[o['ingredient_id']].split(' (')[0].lower()} bottle"
        else:
            objects[o["id"]] = {"punch": "press punch", "rod": "stirring rod"}.get(o["id"], o["id"])

    def what(a: dict) -> str:
        t = a["type"]
        if t == "pour":
            return f"Pour {a['amount_g']:g} g"
        if t == "shake":
            return "Tap and shake" if a["style"] == "tap" else "Shake to mix"
        if t == "press":
            return f"Press at {a['force_kn']:g} kN"
        if t == "read":
            r = a.get("reading", {})
            value = f" = {r['value']:g} {UNIT_WORDS[a['quantity']]}".rstrip() if "value" in r else ""
            return f"Read {QUANTITY_WORDS[a['quantity']]}{value}"
        if t == "scan":
            return "Scan the barcode"
        if t == "wait":
            return f"Wait {_length(a['actual_duration_s'])}"
        return {"move": "Move", "pick": "Pick up", "place": "Put down", "stir": "Stir"}[t]

    def where(a: dict) -> str:
        loc = a.get("from") or a.get("to") or a.get("at") or ""
        if a["type"] == "pour" and a.get("into") in objects:
            return place[a["at"]]
        return place.get(loc, "-") if loc else "-"

    def why(a: dict) -> str:
        if a["outcome"] == "failed":
            return f"FAULT ({a['fault']['cause']}): {a['fault']['detail']}"
        if a["type"] == "wait":
            return a["reason"][0].upper() + a["reason"][1:]
        return a["caption"]

    start = datetime.strptime(setup["calendar"]["start"], "%Y-%m-%d %H:%M") + timedelta(minutes=executed["trial_start_minute"])
    fault = next(a for a in executed["actions"] if a["outcome"] == "failed")
    recovery = [a for a in executed["actions"] if a["origin"] == "recovery"]
    planned_total = sum(executed["step_totals_s"]["planned"].values())
    actual_total = sum(executed["step_totals_s"]["actual"].values())
    jam_at = fault["actual_start_s"] + fault["actual_duration_s"]
    purge = next(a for a in recovery if a["type"] == "wait")
    retry = next(a for a in recovery if a["type"] == "pour")
    res = executed["result"]
    lines = [
        f"# Trial {executed['trial']} in plain words",
        "",
        "> **ILLUSTRATIVE.** The example files are hand-authored and every value is made up.",
        f"> Generated by `tools/make_trial_story.py` from `executed_timeline_example.json` ({executed['executed_id']}). Do not edit by hand: a format check regenerates this text and fails if the file differs.",
        "",
        "## What happened",
        f"- Trial {executed['trial']} started {start:%a %d %b %H:%M} (minute {executed['trial_start_minute']:g} of the run). The robot followed its plan ({executed['plan_id']}) until the binder pour.",
        f"- **The jam:** {_hms(fault['actual_start_s'])} into the trial the {objects[fault['object']]} jammed and only {fault['reading']['value']:g} g of the expected {fault['reading']['expected']:g} g came out.",
        f"- **The recovery ({len(recovery)} extra actions):** tap and shake the bottle ({_length(recovery[0]['actual_duration_s'])}), put it back in its slot, **purge the dispenser for {_length(purge['actual_duration_s'])}**, pick the bottle up again.",
        f"- **The retry:** at {_hms(retry['actual_start_s'])} it poured the remaining {retry['amount_g']:g} g of binder and the balance confirmed it ({fault['reading']['value']:g} + {retry['reading']['value']:g} = {fault['reading']['value'] + retry['reading']['value']:g} g). Nobody was called.",
        f"- The trial then carried on as planned and took {_hms(actual_total)} instead of the planned {_hms(planned_total)}: {_length(actual_total - planned_total)} longer, all of it at the Dispense step.",
        f"- Result: dissolution {res['dissolution_30min_pct']:g} %, hardness {res['hardness_kp']:g} kP, friability {res['friability_pct']:g} % - **{res['verdict']}**.",
        "",
        "## Every action, in order",
        "Time is hours:minutes:seconds since the start of the trial.",
        "",
        "| Time | Action | Object | Station or slot | Planned or recovery | Why |",
        "|---|---|---|---|---|---|",
    ]
    for a in executed["actions"]:
        action = what(a)
        if a["outcome"] == "failed":
            action = f"**{action} - FAILED**"
        elif a["origin"] == "recovery":
            action = f"*{action}*"
        obj = objects.get(a.get("object", ""), "-") if a.get("object") else "-"
        lines.append(f"| {_hms(a['actual_start_s'])} | {action} | {obj} | {where(a)} | {a['origin']} | {why(a)} |")
    lines += ["", f"The fault was found {_hms(jam_at)} into the trial.", ""]
    return "\n".join(lines)


def main() -> int:
    executed = json.loads((FORMATS / "executed_timeline_example.json").read_bytes().decode("utf-8-sig"))
    layout = json.loads((FORMATS / "cell_layout_example.json").read_bytes().decode("utf-8-sig"))
    setup = yaml.safe_load((FORMATS / "setup_example.yaml").read_bytes().decode("utf-8-sig"))
    text = build_story(executed, layout, setup)
    if "--print" in sys.argv:
        print(text)
        return 0
    OUT.write_bytes(text.encode("utf-8"))
    print(f"Wrote {OUT.relative_to(ROOT)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
